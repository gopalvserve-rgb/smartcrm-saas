async function _sendInvoice(tenant, invoice, channels) {
  const platform = {
    name:         (await control.getSetting('PLATFORM_NAME')) || 'SmartCRM',
    supportPhone: (await control.getSetting('SUPPORT_PHONE')) || '',
    supportEmail: (await control.getSetting('SUPPORT_EMAIL')) || ''
  };
  const out = { email: null, whatsapp: null };
  if (channels.email && tenant.contact_email) {
    try {
      await saasMailer.sendMail({
        to: tenant.contact_email,
        subject: `Invoice ${invoice.number} — ${platform.name} renewal (${_fmtINR(invoice.total)})`,
        html: _emailHtml({ tenant, invoice, platform })
      });
      out.email = 'sent';
    } catch (e) {
      out.email = 'err: ' + e.message;
    }
  }
  if (channels.whatsapp && tenant.contact_phone) {
    try {
      await saasWA.sendTemplate({
        to: tenant.contact_phone,
        params: [
          tenant.name || 'Customer',
          invoice.number,
          _fmtINR(invoice.total),
          _fmtDate(invoice.periodEnd)
        ]
      });
      out.whatsapp = 'sent';
    } catch (e) {
      out.whatsapp = 'err: ' + e.message;
    }
  }
  // Log to invoice notes
  try {
    const stamp = new Date().toISOString().slice(0, 19).replace('T', ' ');
    const tag = `[${stamp}] sent: email=${out.email||'skip'} wa=${out.whatsapp||'skip'}`;
    await control.query(
      `UPDATE invoices SET notes = COALESCE(notes, '') || E'\n' || $1, updated_at=NOW() WHERE id=$2`,
      [tag, invoice.id]
    );
  } catch (_) {}
  return out;
}

/** Run one full sweep cycle. Safe to call manually from a super-admin API. */
async function runOnce() {
  if (_running) return { skipped: 'already running' };
  _running = true;
  const out = { scanned: 0, created: 0, sent: 0, errors: [] };
  try {
    const daysBefore = parseInt((await control.getSetting('AUTO_INVOICE_DAYS_BEFORE')) || '0', 10);
    if (!daysBefore || daysBefore < 1) {
      out.skipped = 'AUTO_INVOICE_DAYS_BEFORE not set (>=1 enables)';
      return out;
    }
    const sendEmail = (await control.getSetting('AUTO_INVOICE_SEND_EMAIL')) === '1';
    const sendWa    = (await control.getSetting('AUTO_INVOICE_SEND_WA'))    === '1';

    const tenants = await control.query(
      `SELECT id, name, slug, contact_email, contact_phone, package_id,
              current_period_start, current_period_end, status
         FROM tenants
        WHERE status IN ('active','trialing','past_due')
          AND current_period_end IS NOT NULL
          AND current_period_end <= NOW() + ($1 || ' days')::interval
          AND current_period_end >= NOW() - INTERVAL '2 days'`,
      [String(daysBefore)]
    );
    out.scanned = tenants.rows.length;

    for (const t of tenants.rows) {
      try {
        // Has an invoice already been created for this period?
        const ex = await control.query(
          `SELECT id, number FROM invoices
            WHERE tenant_id=$1 AND period_end::date = $2::date
              AND status IN ('pending','paid','failed')
            LIMIT 1`,
          [t.id, t.current_period_end]
        );
        let invoice;
        if (ex.rows.length) {
          invoice = { id: ex.rows[0].id, number: ex.rows[0].number, _existing: true };
        } else {
          invoice = await _createInvoiceForTenant(t);
          out.created++;
        }

        // Only send for fresh invoices to avoid spamming
        if (!invoice._existing && (sendEmail || sendWa)) {
          const r = await _sendInvoice(t, invoice, { email: sendEmail, whatsapp: sendWa });
          if (r.email === 'sent' || r.whatsapp === 'sent') out.sent++;
        }
      } catch (e) {
        out.errors.push({ tenant: t.slug, err: String(e.message || e).slice(0, 200) });
      }
    }
    return out;
  } finally {
    _running = false;
  }
}

function startSweep() {
  if (_started) return;
  _started = true;
  // First run after 5 min to let server warm up
  setTimeout(() => runOnce().catch(e => console.warn('[saasInvoiceAutoGen]', e.message)), 5 * 60 * 1000);
  setInterval(() => runOnce().catch(e => console.warn('[saasInvoiceAutoGen]', e.message)), RUN_EVERY_MS);
  console.log('[saasInvoiceAutoGen] sweep started (every 6h)');
}

module.exports = { runOnce, startSweep, _sendInvoice, _genInvoiceNumber };
