/* ============================================================================
 * SaaS auto-invoice generator + dispatcher (SAAS_AUTO_INVOICE_v1, 2026-06-27)
 *
 * Daily sweep:
 *   1. Find every active tenant with current_period_end within
 *      AUTO_INVOICE_DAYS_BEFORE (default 7).
 *   2. If no pending/paid invoice already covers that period_end, create one.
 *   3. If AUTO_INVOICE_SEND_EMAIL / _SEND_WA = '1', send via that channel.
 *
 * Load-safe: zero work unless AUTO_INVOICE_DAYS_BEFORE > 0.
 * Idempotent: never duplicates invoices for the same period_end.
 * ============================================================================ */
'use strict';
const control     = require('../control/db');
const saasMailer  = require('../routes/saas/saasMailer');
const saasWA      = require('../routes/saas/saasWhatsApp');

const RUN_EVERY_MS = 6 * 60 * 60 * 1000;  // 6 hours

let _started = false;
let _running = false;

function _fmtINR(n) {
  return '₹' + Number(n || 0).toLocaleString('en-IN', { minimumFractionDigits: 2, maximumFractionDigits: 2 });
}

function _fmtDate(d) {
  if (!d) return '—';
  try { return new Date(d).toLocaleDateString('en-IN', { day:'2-digit', month:'short', year:'numeric' }); }
  catch (_) { return String(d); }
}

async function _genInvoiceNumber() {
  const yr = new Date().getFullYear();
  const r = await control.query(
    `SELECT number FROM invoices WHERE number LIKE $1 ORDER BY id DESC LIMIT 1`,
    [`INV-${yr}-%`]
  );
  let next = 1;
  if (r.rows.length) {
    const m = String(r.rows[0].number).match(/(\d+)$/);
    if (m) next = parseInt(m[1], 10) + 1;
  }
  return `INV-${yr}-${String(next).padStart(6, '0')}`;
}

async function _createInvoiceForTenant(t) {
  // Find the package to get amount
  let amount = 0, pkgName = 'Subscription';
  if (t.package_id) {
    const p = await control.query(`SELECT name, price_inr FROM packages WHERE id=$1`, [t.package_id]);
    if (p.rows.length) { amount = Number(p.rows[0].price_inr) || 0; pkgName = p.rows[0].name; }
  }
  const tax = Math.round(amount * 18) / 100;  // 18% GST
  const total = Math.round((amount + tax) * 100) / 100;
  const number = await _genInvoiceNumber();
  const periodStart = t.current_period_start || new Date(Date.now() - 30*86400000).toISOString();
  const periodEnd   = t.current_period_end   || new Date().toISOString();
  const ins = await control.query(
    `INSERT INTO invoices
       (tenant_id, number, package_id, description, subtotal_inr, tax_inr, total_inr,
        period_start, period_end, status, notes, created_at, updated_at)
     VALUES ($1,$2,$3,$4,$5,$6,$7,$8,$9,'pending',$10, NOW(), NOW())
     RETURNING id, number`,
    [t.id, number, t.package_id || null, pkgName + ' — renewal', amount, tax, total,
     periodStart, periodEnd, 'Auto-generated by SAAS_AUTO_INVOICE_v1']
  );
  return { id: ins.rows[0].id, number: ins.rows[0].number, total, subtotal: amount, tax,
           periodEnd, packageName: pkgName };
}

